/**
 * ticket-context.ts: the facts `flow` knows about a file the agent opens, sent beside the file.
 *
 * A `Read` or an `@` mention of a `ticket.md` under `.flow/tickets/` gets the ticket's header: the
 * effective status, activity, labels, parent, children, what it waits on and the open questions,
 * from `flow tickets get <id> --json`. A `Read` or mention of a wiki folder's `index.md` gets the
 * labels of that folder's findings with their counts, from `flow findings --json`. The text rides
 * as the hook's `context`, which the model reads and the file never holds.
 *
 * Each goes once per window: a window that holds the exact text gets nothing, so a compaction, a
 * restart and a changed header send it again, and a subagent's window counts apart. The hooks are
 * `tool.call` on `Read` and `prompt.mention` (register.ts).
 */
import type { EngineInterface } from 'claude-code'
import { reasonOf } from '../../shared/format'
import { flowHome } from '../../shared/home'
import { heldBy } from '../guides/skill-wiki'

type Brief = { id: string; status: string }

/** The fields of `flow tickets get <id> --json` the header reads. */
export type TicketRecord = {
  id: string
  /** The effective status: `parked` while `heldBy` names the parked group holding it. */
  status: string
  /** The status the file holds. Absent from a `flow` older than this field. */
  storedStatus?: string
  heldBy: string
  activity: string
  labels: string[]
  parent: string
  progress: { done: number; total: number } | null
  blockedBy: { id: string; reason: string }[]
  dependents: Brief[]
  openQuestions: string[]
}

/** The ticket folder and the project root of a `ticket.md` path, or undefined for any other file. */
export function ticketFileOf(path: string): { root: string; number: string } | undefined {
  const found = /^(.*)\/\.flow\/tickets\/(?:archive\/)?(\d+)(?:-[^/]*)?\/ticket\.md$/.exec(path)
  return found ? { root: found[1] || '/', number: String(Number(found[2])) } : undefined
}

/** The wiki folder whose `index.md` the path is, or undefined. */
export function wikiFolderOf(path: string, home: string): string | undefined {
  const found = /^([\w.-]+)\/index\.md$/.exec(path.startsWith(`${home}/wiki/`) ? path.slice(home.length + 6) : '')
  return found?.[1]
}

const row = (key: string, value: string) => `${`${key}:`.padEnd(13)}${value}`
const briefs = (list: readonly { id: string; status?: string; reason?: string }[]) => list.map((b) => `${b.id} (${b.status ?? b.reason})`).join(', ')

/**
 * The header of a ticket: the facts its file does not show, one row each, the empty ones left out, and
 * empty where none is left. The front matter already shows status, activity, labels, parent and the
 * ids it waits on, so status comes only where a parked group overrides it.
 */
export function ticketHeader(r: TicketRecord, path: string): string {
  const rows = [
    r.heldBy && row('status', `${r.storedStatus ?? r.status} (held by ${r.heldBy})`),
    r.progress && row('children', `${r.progress.done}/${r.progress.total} done`),
    r.blockedBy.length && row('waits on', briefs(r.blockedBy)),
    r.dependents.length && row('dependents', briefs(r.dependents)),
    r.openQuestions.length && row('questions', `${r.openQuestions.length} open (${r.openQuestions.join(', ')})`),
  ].filter((line): line is string => typeof line === 'string' && line !== '')
  if (!rows.length) return ''
  return [
    `[Auto] ${r.id} as \`flow\` reports it. These lines are generated, not part of ${path}: never copy them into the file. Change these fields with \`flow tickets\` alone.`,
    '```text',
    ...rows,
    '```',
  ].join('\n')
}

/** The labels of a wiki folder's findings, the most used first, with a count for the findings that carry none. */
export function wikiLabels(folder: string, home: string, findings: readonly { labels?: string[] }[]): string {
  const counts = new Map<string, number>()
  let bare = 0
  for (const f of findings) {
    if (!f.labels?.length) bare += 1
    for (const label of f.labels ?? []) counts.set(label, (counts.get(label) ?? 0) + 1)
  }
  const labels = [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([label, count]) => `${label} ${count}`)
  if (bare) labels.push(`no label ${bare}`)
  const head = `[Auto] The findings in ${home}/wiki/${folder}/findings/, by label, generated by \`flow\`. \`flow findings -- "wiki:${folder} label:<label>"\` lists one label's.`
  return findings.length ? `${head}\n${labels.join(' · ')}` : `[Auto] ${home}/wiki/${folder}/findings/ holds no findings.`
}

/** The JSON a `flow` command prints, or undefined where it cannot run or prints an error. */
async function flowJson($: EngineInterface, args: string[], cwd: string): Promise<unknown> {
  const ran = await $.process.run(['flow', ...args, '--json'], { cwd, timeoutMs: 10000 })
  const data = JSON.parse(ran.stdout) as { error?: string }
  return data && typeof data === 'object' && 'error' in data ? undefined : data
}

/** The text a file's `Read` or mention adds, before the window check: a ticket's header, a wiki folder's labels, else none. */
async function contextText($: EngineInterface, path: string): Promise<string | undefined> {
  const ticket = ticketFileOf(path)
  if (ticket) {
    const record = (await flowJson($, ['tickets', 'get', ticket.number], ticket.root)) as TicketRecord | undefined
    return record?.id ? ticketHeader(record, path) : undefined
  }
  const home = await flowHome($)
  const folder = wikiFolderOf(path, home)
  if (!folder) return undefined
  const findings = await flowJson($, ['findings', '--', `wiki:${folder}`], home)
  return Array.isArray(findings) ? wikiLabels(folder, home, findings as { labels?: string[] }[]) : undefined
}

/** The text for a file the agent opens, none where the window already holds it or `flow` could not answer. */
export async function fileContext($: EngineInterface, path: unknown, agentId: string | undefined): Promise<string | undefined> {
  if (typeof path !== 'string' || !/\/(ticket|index)\.md$/.test(path)) return undefined
  try {
    const text = await contextText($, path)
    if (!text || (await heldBy($, agentId)).text.includes(text)) return undefined
    return text
  } catch (error) {
    $.ui.log(`file context not sent: ${reasonOf(error)}`)
    return undefined
  }
}

/** A `tool.call` or `prompt.mention` result with the file's text added to its `context`. A refusal or a failed read passes untouched. */
export async function withFileContext<R extends { deny?: string; isError?: boolean; context?: readonly string[] }>(
  $: EngineInterface,
  path: unknown,
  agentId: string | undefined,
  done: R,
): Promise<R> {
  if (done.deny !== undefined || done.isError) return done
  const text = await fileContext($, path, agentId)
  return text ? { ...done, context: [...(done.context ?? []), text] } : done
}
